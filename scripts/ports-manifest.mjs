/**
 * scripts/ports-manifest.mjs — the component-port drift ledger.
 *
 * kit/ports/manifest.json records a content hash for every
 * app/components/Tux*.vue plus the hash each framework port was last
 * generated against. The ports-sync workflow (tier 2 of
 * design/kit-pipeline.md) runs this on every merge to main that
 * touches components: when a component is new or its hash moved, the
 * workflow commits the updated ledger + QUEUE.md to a bot branch and
 * opens a PR — which the existing ai-review superPOD panel then
 * reviews like any other PR. Zero new access: detection is pure
 * computation, correctness review reuses the panel already wired
 * into CI.
 *
 * Modes:
 *   --seed   record every component at its current hash as the
 *            baseline (no queue entries). Run once at adoption.
 *   (none)   sync: update hashes, queue changed/new components,
 *            rewrite QUEUE.md. Prints drifted names; exits 0 always
 *            (the workflow decides what to do with the diff).
 *   --check  exit 1 if the committed manifest is missing components
 *            or carries ghosts (the catalog-test discipline).
 */

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const COMPONENTS = path.join(ROOT, "app/components");
const MANIFEST = path.join(ROOT, "kit/ports/manifest.json");
const QUEUE = path.join(ROOT, "kit/ports/QUEUE.md");

/** Framework ports the ledger tracks. Extend as targets come online. */
export const PORT_TARGETS = ["react"];

function componentHashes() {
  const out = {};
  for (const f of fs.readdirSync(COMPONENTS).filter((f) => f.endsWith(".vue")).sort()) {
    const name = f.replace(/\.vue$/, "");
    const body = fs.readFileSync(path.join(COMPONENTS, f));
    out[name] = crypto.createHash("sha256").update(body).digest("hex").slice(0, 16);
  }
  return out;
}

function loadManifest() {
  try {
    return JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  } catch {
    return { _note: "", components: {} };
  }
}

function writeManifest(m) {
  m._note =
    "GENERATED ledger — scripts/ports-manifest.mjs. sourceHash = current " +
    "Tux*.vue content hash; ports.<target>.hash = the source hash that " +
    "port was last generated/verified against (null = never ported).";
  fs.mkdirSync(path.dirname(MANIFEST), { recursive: true });
  fs.writeFileSync(MANIFEST, JSON.stringify(m, null, 2) + "\n");
}

export function sync({ seed = false } = {}) {
  const hashes = componentHashes();
  const m = loadManifest();
  const drifted = [];
  const removed = Object.keys(m.components ?? {}).filter((n) => !(n in hashes));
  for (const name of removed) delete m.components[name];
  m.components ??= {};
  for (const [name, hash] of Object.entries(hashes)) {
    const entry = m.components[name] ?? {
      sourceHash: null,
      ports: Object.fromEntries(PORT_TARGETS.map((t) => [t, { hash: null }])),
    };
    if (entry.sourceHash !== hash) {
      if (!seed && entry.sourceHash !== null) drifted.push(name);
      if (!seed && entry.sourceHash === null) drifted.push(name);
      entry.sourceHash = hash;
    }
    m.components[name] = entry;
  }
  writeManifest(m);
  writeQueue(m);
  return { drifted, removed };
}

function writeQueue(m) {
  const rows = [];
  for (const [name, entry] of Object.entries(m.components)) {
    for (const target of PORT_TARGETS) {
      const port = entry.ports?.[target] ?? { hash: null };
      if (port.hash === null) rows.push(`| ${name} | ${target} | never ported |`);
      else if (port.hash !== entry.sourceHash)
        rows.push(`| ${name} | ${target} | STALE (source moved since port) |`);
    }
  }
  const body = [
    "# Port queue",
    "",
    "GENERATED by scripts/ports-manifest.mjs — components whose",
    "framework ports are missing or stale. The ports-sync workflow",
    "keeps this current; entries leave the queue when a port lands",
    "with a matching source hash in manifest.json.",
    "",
    "| Component | Target | Status |",
    "|---|---|---|",
    ...(rows.length ? rows : ["| *(queue empty — every port is current)* | | |"]),
    "",
  ].join("\n");
  fs.writeFileSync(QUEUE, body);
}

export function check() {
  const hashes = componentHashes();
  const m = loadManifest();
  const missing = Object.keys(hashes).filter((n) => !(n in (m.components ?? {})));
  const ghosts = Object.keys(m.components ?? {}).filter((n) => !(n in hashes));
  return { missing, ghosts };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const mode = process.argv[2];
  if (mode === "--seed") {
    sync({ seed: true });
    console.log("seeded manifest at current component hashes");
  } else if (mode === "--check") {
    const { missing, ghosts } = check();
    if (missing.length || ghosts.length) {
      console.error("manifest drift — missing:", missing, "ghosts:", ghosts);
      process.exit(1);
    }
    console.log("✓ ports manifest matches the component census");
  } else {
    const { drifted, removed } = sync();
    console.log(JSON.stringify({ drifted, removed }));
  }
}
